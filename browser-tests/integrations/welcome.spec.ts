import { expect, test } from "@playwright/test";
test("public welcome has clear audience actions and a responsive illustration", async ({ page }, info) => {
  await page.emulateMedia({ reducedMotion: "reduce" });
  await page.goto("/");
  await expect(page.getByRole("heading", { level: 1 })).toHaveText("Your identity.In your pocket.");
  const navigation = page.getByRole("navigation", { name: "Welcome navigation" });
  await expect(navigation.getByRole("link", { name: "Vendor log in", exact: true })).toHaveAttribute("href", "/vendor/sign-in");
  await expect(navigation.getByRole("link", { name: "Staff log in", exact: true })).toHaveAttribute("href", "/sign-in");
  const funding = navigation.getByRole("link", { name: "Fund a student", exact: true });
  await expect(funding).toHaveAttribute("href", "/fund");
  await expect(funding).toBeVisible();
  await expect(navigation.getByRole("link", { name: "Students", exact: true })).toHaveCount(0);
  await expect(page.getByRole("link", { name: "Register your business" })).toHaveAttribute("href", "/vendor/sign-up");
  const vendors = page.locator("#vendors");
  await expect(vendors.getByRole("link", { name: "Vendor log in", exact: true })).toHaveAttribute("href", "/vendor/sign-in");
  await expect(page.getByRole("link", { name: "University staff log in" })).toHaveAttribute("href", "/sign-in");
  await expect(page.getByRole("main").getByRole("link", { name: "Fund a student", exact: true })).toHaveAttribute("href", "/fund");
  await expect(page.getByText(/approved wallet app/)).toBeVisible();
  expect(await page.locator('a[href$=".apk"]').count()).toBe(0);
  await page.keyboard.press("Tab"); await expect(page.getByRole("link", { name: "Skip to content" })).toBeFocused();
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true);
  expect(await page.locator(".welcome-art").evaluate(el => getComputedStyle(el).animationName)).toBe("none");
  await page.getByRole("heading", { level: 1 }).click();
  await page.screenshot({ path: info.outputPath(`welcome-${info.project.name}.png`), fullPage: true });
});
